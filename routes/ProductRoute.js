const express = require('express');
const upload = require('../middlewares/upload');
const { getProduct, createProduct, updateProduct, deleteProduct } = require('../controllers/ProductController');
const router = express.Router();
const { authenticate, authorize } = require('../middlewares/auth');
router.use(authenticate, authorize('admin'));
router.get('/', getProduct);
const productUpload = [upload.fields([{ name: 'image', maxCount: 1 }, { name: 'galleryImages', maxCount: 8 }]), (req, res, next) => { req.file = req.files?.image?.[0]; next(); }];
router.post('/', ...productUpload, createProduct);
router.put('/:id', ...productUpload, updateProduct);
router.delete('/:id', deleteProduct);
module.exports = router;
